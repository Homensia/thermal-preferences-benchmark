"""Captions of the paper figures, generated with the figures (``captions/<figure stem>.tex``).

Each file holds one ``\\caption{...}\\label{...}`` to paste or ``\\input`` in the figure environment of the
manuscript, preceded by comments giving the figure files and the width at which the figure is drawn (every
figure is drawn at its print size, so that no text falls below 7 pt; it must be included at that width).
The captions state what the reader needs: the vote codes of TSV-3 and TPV, the coverage of each index, the QWK of a constant predictor,
the seed handling, the colour scales of the confusion matrices, the importance measures of RF and XGBoost,
and the meaning of the whiskers and reference lines of the NN figure. Every caption goes through the wording
guard (``OutputDir.write_text``): heat-balance models, no banned word.
"""
from __future__ import annotations

from typing import Dict, Iterable, List, Optional

from .metrics import DATASET_NAME, TARGET_LABEL, TARGETS, VOTE_MEANING

TEXT_WIDTH = "\\linewidth"                       # 510 pt in the 5p final layout (bar_charts.PAGE_WIDTH_IN)
FTT_DEFINITION = "FTT: FT-Transformer"
MODELS_SENTENCE = ("RF: random forest; XGBoost: gradient-boosted trees; SVM: support vector machine; ANN: "
                   "multilayer perceptron; FTT: FT-Transformer; FTT+RF and FTT+XGBoost: RF and XGBoost heads on "
                   "the FTT embeddings")


def num(v) -> str:
    return f"{int(v):,}".replace(",", "\\,")


def _and(items: List[str]) -> str:
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def vote_codes(targets: Iterable[str] = ("TSV_3p", "thermal_preference")) -> str:
    """'Vote codes: TSV-3 $-1$ cool side (TSV-7 $-3$ to $-1$), ...; TPV $-1$ want cooler, ...'."""
    parts = []
    for t in targets:
        codes = []
        for v, meaning in VOTE_MEANING[t].items():
            extra = ""
            if t == "TSV_3p" and v != 0:
                extra = " (TSV-7 $-3$ to $-1$)" if v < 0 else " (TSV-7 $+1$ to $+3$)"
            codes.append(f"${'+' if v > 0 else ''}{v}$ {meaning}{extra}")
        parts.append(f"{TARGET_LABEL[t]} " + ", ".join(codes))
    return "Vote codes: " + "; ".join(parts) + "."


def caption_file(label: str, files: str, width: str, text: str) -> str:
    return (f"% Caption of {label} ({files}). Generated by analysis/paper_figures with the figure.\n"
            f"% The figure is drawn at its print size: include it at width={width} (every text then >= 7 pt).\n"
            f"\\caption{{{text}}}\\label{{{label}}}\n")


def distributions(n: Dict[str, int]) -> str:
    names = [f"{DATASET_NAME[k]} ($n={num(v)}$)" for k, v in n.items()]
    return (f"Distribution of the votes in {_and(names)}, one panel per target (rows: TSV-7, TSV-3, TPV). "
            "TSV-7 codes: $-3$ cold, $-2$ cool, $-1$ slightly cool, 0 neutral, $+1$ slightly warm, $+2$ warm, "
            f"$+3$ hot. {vote_codes()} Each vote value keeps one colour in every panel; a class without any "
            "vote is drawn as an empty bar at 0.")


def phase1(key: str, tpv_identical: Optional[List[str]] = None, kind: str = "bars") -> str:
    """``kind``: "bars" (figure) or "rows" (table)."""
    what = ("Haghirad-aligned RF configurations (NotOpt: 225 trees, depth 25; Opt: per-target optimum of "
            "Haghirad et al., 2018 v2 release)" if key == "haghirad" else
            "high-capacity RF configurations (600 trees, depth 25, min split 10, min leaf 2)")
    text = (f"Phase~1 reproduction grid: {what}; 12 features, one-hot encoding, no random over-sampling. "
            f"Datasets: {DATASET_NAME['ASHRAE_2018']} and {DATASET_NAME['ASHRAE_2022']}. Suffix: class weighting "
            "(NoCW none, Bal balanced, BalSub balanced subsample). One run per configuration (the pinned Phase~1 "
            "grid). QWK: quadratically weighted Cohen's kappa.")
    if tpv_identical:
        text += (" For TPV, Haghirad's optimum is the NotOpt setting itself (225 trees, depth 25), so the Opt "
                 f"and NotOpt {kind} are equal on " + _and(tpv_identical) + ".")
    return text


def phase2(seeds_txt: str, n_test: int, hybrids: bool) -> str:
    models = MODELS_SENTENCE if hybrids else MODELS_SENTENCE.split("; FTT+RF")[0]
    return (f"Phase~2 in-domain performance on {DATASET_NAME['ASHRAE_2022']} (17 features; archived stratified "
            f"80/20 split; test set of {num(n_test)} votes). {seeds_txt}. Point estimates of each model; the "
            "differences between models are assessed with paired bootstrap intervals in the text, not from these "
            f"bars. {models}. QWK: quadratically weighted Cohen's kappa.")


def confusion(target: str, seed_txt: str, vmax: int, n_test: int) -> str:
    codes = (" TSV-7 codes: $-3$ cold to $+3$ hot." if target == "thermal_sensation"
             else " " + vote_codes([target]))
    return (f"{TARGET_LABEL[target]} confusion matrices of the five Phase~2 models on the "
            f"{DATASET_NAME['ASHRAE_2022']} test set ({num(n_test)} votes; model {seed_txt}); rows: true vote, "
            "columns: predicted vote, cells: counts. The colour scale is shared by the five panels (0 to "
            f"{num(vmax)}), so the shading can be compared across models.{codes} {FTT_DEFINITION}.")


def indices(coverage: Dict[str, Dict[str, float]], n_test: int) -> str:
    """``coverage``: index -> target -> share of the test votes on the validity mask."""
    parts = []
    for idx, by_t in coverage.items():
        vals = sorted({round(100 * v) for v in by_t.values()})
        parts.append(f"{idx.replace('_', chr(92) + '_')} {'--'.join(str(v) for v in vals)}\\,\\%")
    targets = sorted({t for by_t in coverage.values() for t in by_t}, key=TARGETS.index)
    return ("Accuracy of the heat-balance models (PMV, PTS\\_SET, PTS\\_PET) and adaptive heat-balance models "
            f"(aPMV, ePMV) on the Phase~2 test split ({DATASET_NAME['ASHRAE_2022']}, {num(n_test)} votes), "
            f"{_and([TARGET_LABEL[t] for t in targets])}. Each model is evaluated only on the test votes whose "
            "inputs lie in its validity range, so the bars rest on different subsets of votes: coverage "
            f"(printed under each bar) {_and(parts)}.")


def feature_importance_heatmap(seeds: Iterable[int]) -> str:
    return ("Feature importance of RF and XGBoost (Phase~2, " + DATASET_NAME["ASHRAE_2022"] + "), mean over "
            f"model seeds {_and([str(s) for s in seeds])}. RF: impurity-based importance (mean decrease in "
            "impurity, MDI); XGBoost: gain-based importance (mean gain of the splits on the feature). The two "
            "measures are on different scales: each importance is normalised to sum to 1 within its model and "
            "target, the cell text is that share, and the colour is the share divided by the largest share of "
            "its column, so colours compare features within a column, not across columns. One-hot parts are "
            "summed per variable. EMA weather: exponential moving averages over 28 days of outdoor temperature, "
            "outdoor relative humidity, precipitation, sunshine duration and wind speed.")


def feature_importance_bars(seeds: Iterable[int]) -> str:
    return ("Feature importance per model and target (Phase~2, " + DATASET_NAME["ASHRAE_2022"] + "), mean over "
            f"model seeds {_and([str(s) for s in seeds])}, normalised to sum to 1. RF: impurity-based importance "
            "(MDI); XGBoost: gain-based importance; the two measures are not on the same scale.")


def phase3(n: Dict[str, int]) -> str:
    cohorts = _and([f"{c} ($n={num(v)}$)" for c, v in n.items()])
    return (f"Phase~3 zero-shot transfer to {cohorts}: the Phase~2 RF, XGBoost and FTT models "
            f"({DATASET_NAME['ASHRAE_2022']}, model seed 42) applied without retraining. Majority class: the most "
            "frequent vote of the cohort predicted for all its votes, a descriptive reference that uses the "
            "cohort labels. A constant predictor has QWK $=0$ by construction, so the majority-class bar of the "
            f"QWK panel has zero height. {FTT_DEFINITION}. QWK: quadratically weighted Cohen's kappa.")


def nn(n: int, seeds_txt: str, cases: bool, hybrids: bool, nn_line: bool = True) -> str:
    text = (f"Test accuracy of the Phase~2 models ({DATASET_NAME['ASHRAE_2022']} test set; bars: {seeds_txt[0].lower()}"
            f"{seeds_txt[1:]}) beside two vote-agreement rates of the {num(n)} cohort votes (vertical lines). "
            "Whiskers: range of the test accuracy over the model seeds (not a confidence interval); a model "
            "with one seed has no whisker. ")
    if nn_line:
        text += ("Red dashed line: share of the votes equal to the vote of their nearest neighbour ($1-D_1$; "
                 f"each of the {num(n)} votes against the {num(n - 1)} other votes, Euclidean distance on the 12 "
                 "standardised variables, categorical variables integer-coded). ")
    text += ("Grey dotted line: chance agreement $\\sum_c p_c^2$ of two votes drawn at random ($p_c$: class "
             f"shares of the {num(n)} cohort votes). The lines are descriptive statistics of the votes on the "
             "full cohort, not accuracies of a model and not limits on the accuracy of a model. Models in the "
             "same order in every panel.")
    if hybrids:
        text += " Hybrid models: RF and XGBoost heads on the FTT embeddings."
    text += f" {FTT_DEFINITION}."
    if cases:
        text += (" Case B: share of groups of identical feature vectors whose votes all agree; Case C: share of "
                 "vote pairs within tight margins that agree. Each is printed with its own chance agreement on "
                 "the same groups / pairs (open circle; Case B: mean over the groups of $\\sum_c q_c^{n_g}$; "
                 "Case C: $\\sum_c p_c^2$, each vote counted once per pair) and its number of groups / pairs.")
    return text
