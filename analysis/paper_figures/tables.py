"""LaTeX tables of the paper.

Restored from the table writers of the pre-revision code (``analysis/finalize_paper_rerun.py``:
``write_table_phase1_haghirad``, ``write_table_phase2_indomain``,
``write_table_phase2_baselines``, ``write_table_phase3_direct``,
``write_table_phase3_adaptive``) with minimal adaptation:

* they return the LaTeX text instead of writing it (the caller writes it
  exclusively, after the wording check) and take frames already built from the
  revision outputs (``rerun_2026-10-XX_v2``), not the pre-revision directory layout;
* column order follows the manuscript tables (Dataset, Target, Config / Model);
* Phase 2 values are seed means; Phase 3 adaptive rows are pooled over the 20
  dev/test splits of each regime; the index table adds the coverage of each
  index (its validity mask) and drops aPTS / ePTS (not restored);
* heat-balance terminology ("heat-balance models"); captions free of the banned wording;
* one name per model and dataset (``metrics.MODEL_NAME`` / ``DATASET_NAME``); no model is set in bold
  (a bold "best" would invite a ranking on margins that the paired bootstrap contrasts do not support;
  the table gives point estimates, the differences are assessed in the text).

``nn_analysis_table`` is new: the paper's NN table, E9b (pre-revision
definitions, F12, full cohort): primary 1-NN disagreement, Case B and Case C,
each beside its chance reference. The Phase 3 tables carry a
majority-class row.
"""
from __future__ import annotations

from typing import List, Optional

import numpy as np
import pandas as pd

from .metrics import DATASET_NAME, TARGET_LABEL, TARGETS

PHASE1_DATASET_DISPLAY = {k: DATASET_NAME[k] for k in ("ASHRAE_2018", "ASHRAE_2022")}
PHASE1_HAGHIRAD_CONFIGS = ["Haghirad_NotOpt_NoCW", "Haghirad_NotOpt_Bal", "Haghirad_NotOpt_BalSub",
                           "Haghirad_Opt_NoCW", "Haghirad_Opt_Bal", "Haghirad_Opt_BalSub"]
PHASE1_HIGHCAP_CONFIGS = ["HighCap_NoCW", "HighCap_Bal", "HighCap_BalSub"]
COHORTS = ["Moujalled", "Hostein"]
METRIC_HEADER = "Accuracy & Macro-F1 & Weighted-F1 & QWK"


def safe_dec(x, decimals=3):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    return "--" if np.isnan(v) else f"{v:.{decimals}f}"


def _tex(s: str) -> str:
    return str(s).replace("_", r"\_").replace("%", r"\%")


def _metrics(row) -> str:
    return " & ".join(safe_dec(row[c]) for c in ("accuracy", "macro_f1", "weighted_f1", "qwk"))


def phase1_table(grid: pd.DataFrame, configs: List[str], label: str, caption: str) -> str:
    sub = grid[(grid["encoding"] == "onehot") & (grid["ros"].astype(str) == "False")
               & grid["config"].isin(configs)].copy()
    if len(sub) != len(configs) * 2 * 3:
        raise ValueError(f"Phase 1 grid: expected {len(configs) * 6} rows for {label}, got {len(sub)}")
    sub["__ds"] = sub["dataset"].map({"ASHRAE_2018": 0, "ASHRAE_2022": 1})
    sub["__tg"] = sub["target"].map({t: i for i, t in enumerate(TARGETS)})
    sub["__cf"] = sub["config"].map({c: i for i, c in enumerate(configs)})
    sub = sub.sort_values(["__ds", "__tg", "__cf"])
    lines = [
        "% Phase 1: Haghirad reproduction grid (RF, 12 features, one-hot, ROS off); not rerun in the revision.",
        "% Source: results/phase1/experiment_grid_full.csv (pinned SHA-256).",
        "% Generated by analysis/paper_figures (restored write_table_phase1_haghirad).",
        "\\begin{table}[H]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
        "\\renewcommand{\\arraystretch}{0.95}", "\\adjustbox{max width=\\linewidth}{%",
        "\\begin{tabular}{p{2.6cm}llcccc}", "\\toprule", f"Dataset & Target & Config & {METRIC_HEADER} \\\\",
        "\\midrule"]
    last_ds = last_tg = None
    for _, row in sub.iterrows():
        ds = PHASE1_DATASET_DISPLAY[row["dataset"]] if row["dataset"] != last_ds else ""
        tg = TARGET_LABEL[row["target"]] if (row["dataset"], row["target"]) != (last_ds, last_tg) else ""
        lines.append(f"{ds} & {tg} & {_tex(row['config'])} & {_metrics(row)} \\\\")
        last_ds, last_tg = row["dataset"], row["target"]
    lines += ["\\bottomrule", "\\end{tabular}%", "}", f"\\caption{{{caption}}}\\label{{{label}}}",
              "\\end{table}"]
    return "\n".join(lines) + "\n"


def _and(items: List[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def seeds_sentence(df: pd.DataFrame) -> str:
    """'Mean over model seeds 42, 43 and 44 (SVM: seed 42 only)' built from the ``seeds`` lists averaged."""
    sets = {}
    for _, r in df.iterrows():
        sets.setdefault(tuple(sorted(int(s) for s in r["seeds"])), []).append(str(r["model"]))
    if not sets:
        raise ValueError("no seed list")
    common = max(sets, key=lambda k: (len(sets[k]), len(k)))
    def seeds_txt(k):
        return f"seed {k[0]} only" if len(k) == 1 else "seeds " + _and([str(x) for x in k])
    text = ("Value of model seed " + str(common[0]) if len(common) == 1
            else "Mean over model seeds " + _and([str(x) for x in common]))
    others = []
    for k, models in sets.items():
        if k != common:
            others.append(f"{_and(list(dict.fromkeys(models)))}: {seeds_txt(k)}")
    return text + (f" ({'; '.join(others)})" if others else "")


def phase2_table(df: pd.DataFrame, model_order: List[str], pending_note: Optional[str] = None,
                 n_test: int = 3045) -> str:
    """``df``: target, model (display name), accuracy, macro_f1, weighted_f1, qwk, seeds (list averaged)."""
    lines = [
        "% Phase 2 in-domain (E1; hybrids: E10), ASHRAE-2022 v2.1.0, 17 features, archived 80/20 split.",
        "% Values: mean over the seeds listed in the companion CSV (per-seed rows of aggregates/E1_metrics.csv;",
        "% weighted-F1 from each seed's confusion matrix). Generated by analysis/paper_figures"
        " (restored write_table_phase2_indomain)."]
    if pending_note:
        lines.append(f"% PENDING: {pending_note}")
    lines += ["\\begin{table}[H]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
              "\\renewcommand{\\arraystretch}{0.95}", "\\begin{tabular}{llcccc}", "\\toprule",
              f"Target & Model & {METRIC_HEADER} \\\\", "\\midrule"]
    for t in TARGETS:
        sub = df[df["target"] == t].copy()
        if sub.empty:
            continue
        sub["__r"] = sub["model"].map({m: i for i, m in enumerate(model_order)})
        sub = sub.sort_values("__r")
        first = True
        for _, row in sub.iterrows():            # no bold: point estimates, no ranking
            lines.append(f"{TARGET_LABEL[t] if first else ''} & {row['model']} & {_metrics(row)} \\\\")
            first = False
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    n_txt = f"{int(n_test):,}".replace(",", "\\,")
    hybrids = any("+" in str(m) for m in df["model"])
    caption = ("Phase~2 in-domain performance on ASHRAE-2022 (file v2.1.0; 17 features; archived stratified "
               f"80/20 split). {seeds_sentence(df)}; test set of {n_txt} votes. Point estimates of each model; "
               "the differences between models are assessed with paired bootstrap intervals in the text, not from "
               "this table. FTT: FT-Transformer"
               + ("; FTT+RF and FTT+XGBoost: RF and XGBoost heads on the FTT embeddings." if hybrids else "."))
    lines += ["\\end{tabular}", f"\\caption{{{caption}}}\\label{{tab:phase2_indomain}}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def indices_table(df: pd.DataFrame, index_order: List[str], pending_note: Optional[str] = None) -> str:
    """``df``: index, target, coverage, n, accuracy, macro_f1, weighted_f1, qwk."""
    work = df.copy()
    work["__i"] = work["index"].map({m: i for i, m in enumerate(index_order)})
    work["__t"] = work["target"].map({t: i for i, t in enumerate(TARGETS)})
    work = work.sort_values(["__i", "__t"])
    lines = [
        "% Heat-balance models (PMV, SET, PET) and adaptive heat-balance models (aPMV, ePMV) on the Phase 2 test split,",
        "% each on its own validity mask (E7: PMV, aPMV; E7b: PTS_SET, PTS_PET, ePMV).",
        "% Generated by analysis/paper_figures (restored write_table_phase2_baselines)."]
    if pending_note:
        lines.append(f"% PENDING: {pending_note}")
    lines += ["\\begin{table}[H]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
              "\\renewcommand{\\arraystretch}{0.95}", "\\begin{tabular}{llccccc}", "\\toprule",
              f"Index & Target & Coverage & {METRIC_HEADER} \\\\", "\\midrule"]
    last = None
    for _, row in work.iterrows():
        ind = _tex(row["index"]) if row["index"] != last else ""
        cov = f"{100 * float(row['coverage']):.0f}\\,\\%"
        lines.append(f"{ind} & {TARGET_LABEL[row['target']]} & {cov} & {_metrics(row)} \\\\")
        last = row["index"]
    caption = ("Heat-balance models (PMV, PTS\\_SET, PTS\\_PET) and adaptive heat-balance models (aPMV, ePMV) on "
               "the Phase~2 test split (ASHRAE-2022, 3\\,045 votes). Each model is evaluated on the test votes where "
               "its inputs lie in its validity range (coverage = share of the test votes), so the rows rest on "
               "different subsets of votes; a vote outside it is never assigned a class.")
    e7b = [i for i in ("ePMV", "PTS_SET", "PTS_PET") if i in set(work["index"])]
    if not (work["target"] == "thermal_preference").any():
        caption += " The models are evaluated on TSV-7 and TSV-3 only."
    elif e7b:
        caption += (f" {_tex(_and(e7b))} {'is' if len(e7b) == 1 else 'are'} evaluated on TSV-7 and TSV-3 only.")
    if (work["target"] == "thermal_preference").any():
        caption += (" TPV class from the index value $x$: $-1$ if $x>0.5$, $+1$ if $x<-0.5$, 0 otherwise.")
    if "epmv_e" in work.columns and (work["index"] == "ePMV").any():
        ep = work[work["index"] == "ePMV"]
        parts = [f"{TARGET_LABEL[r['target']]} $e={float(r['epmv_e']):.3f}"
                 + ("^{\\dagger}$" if bool(r["epmv_e_flag_outside_range"]) else "$") for _, r in ep.iterrows()]
        caption += (" ePMV expectancy factor $e$ fitted by least squares through the origin on the training votes, "
                    "not bounded: " + ", ".join(parts) + ".")
        if ep["epmv_e_flag_outside_range"].astype(bool).any():
            caption += " $^{\\dagger}$Outside the range 0.5--1.0 of Fanger and Toftum."
        caption += (" PTS\\_SET, PTS\\_PET and ePMV values beyond the seven-point scale ($\\geq 3.5$ or "
                    "$< -3.5$) are assigned the end class.")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{caption}}}\\label{{tab:heat_balance_indices}}",
              "\\end{table}"]
    return "\n".join(lines) + "\n"


def phase3_direct_table(df: pd.DataFrame, model_order: List[str]) -> str:
    """``df``: cohort, target, model (display), n, accuracy, macro_f1, weighted_f1, qwk."""
    work = df.copy()
    work["__c"] = work["cohort"].map({c: i for i, c in enumerate(COHORTS)})
    work["__t"] = work["target"].map({t: i for i, t in enumerate(TARGETS)})
    work["__m"] = work["model"].map({m: i for i, m in enumerate(model_order)})
    work = work.sort_values(["__c", "__t", "__m"])
    lines = ["% Phase 3 zero-shot transfer (E6, full cohorts), E1 seed-42 models.",
             "% Generated by analysis/paper_figures (restored write_table_phase3_direct).",
             "\\begin{table}[H]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\renewcommand{\\arraystretch}{0.95}", "\\begin{tabular}{lllcccc}", "\\toprule",
             f"Dataset & Target & Model & {METRIC_HEADER} \\\\", "\\midrule"]
    last_c = last_t = None
    for _, row in work.iterrows():
        c = row["cohort"] if row["cohort"] != last_c else ""
        t = TARGET_LABEL[row["target"]] if (row["cohort"], row["target"]) != (last_c, last_t) else ""
        lines.append(f"{c} & {t} & {row['model']} & {_metrics(row)} \\\\")
        last_c, last_t = row["cohort"], row["target"]
    n = {c: int(work[work["cohort"] == c]["n"].iloc[0]) for c in COHORTS if (work["cohort"] == c).any()}
    caption = ("Phase~3 zero-shot transfer to Moujalled ($n={}$) and Hostein ($n={}$): the Phase~2 models "
               "(ASHRAE-2022 v2.1.0, model seed 42) applied without retraining. FTT: FT-Transformer.").format(
                   n.get("Moujalled", "--"), n.get("Hostein", "--"))
    if (work["model"] == "Majority class").any():
        caption += (" Majority class: the most frequent vote of the cohort predicted for all its votes (a "
                    "descriptive reference that uses the cohort labels; QWK is 0 by construction).")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{caption}}}\\label{{tab:phase3_direct}}",
              "\\end{table}"]
    return "\n".join(lines) + "\n"


PHASE3_REGIME_LABEL = {"80-20": "80\\% dev -- 20\\% test", "20-80": "20\\% dev -- 80\\% test"}


def phase3_adaptive_table(df: pd.DataFrame, variant_order: List[str]) -> str:
    """``df``: cohort, target, regime, variant (display), n, accuracy, macro_f1, weighted_f1, qwk."""
    work = df.copy()
    work["__c"] = work["cohort"].map({c: i for i, c in enumerate(COHORTS)})
    work["__t"] = work["target"].map({t: i for i, t in enumerate(TARGETS)})
    work["__v"] = work["variant"].map({v: i for i, v in enumerate(variant_order)})
    work["__r"] = work["regime"].map({"80-20": 0, "20-80": 1})
    work = work.sort_values(["__c", "__t", "__v", "__r"])
    lines = ["% Phase 3 adaptive transfer (E6): rows pooled over the 20 dev/test splits of each regime.",
             "% Generated by analysis/paper_figures (restored write_table_phase3_adaptive).",
             "\\begin{table}[H]", "\\centering", "\\scriptsize", "\\renewcommand{\\arraystretch}{0.95}",
             "\\adjustbox{max width=\\linewidth}{%", "\\begin{tabular}{llllcccc}", "\\toprule",
             f"Dataset & Target & Variant & Regime & {METRIC_HEADER} \\\\", "\\midrule"]
    last = (None, None, None)
    for _, row in work.iterrows():
        c = row["cohort"] if row["cohort"] != last[0] else ""
        t = TARGET_LABEL[row["target"]] if (row["cohort"], row["target"]) != last[:2] else ""
        v = row["variant"] if (row["cohort"], row["target"], row["variant"]) != last else ""
        lines.append(f"{c} & {t} & {v} & {PHASE3_REGIME_LABEL[row['regime']]} & {_metrics(row)} \\\\")
        last = (row["cohort"], row["target"], row["variant"])
    caption = ("Adaptive transfer on Moujalled and Hostein. RF and XGBoost are retrained on the target-domain "
               "development split; FTT-Head-only adapts the classification head of the Phase~2 FTT (FT-Transformer), "
               "FTT-Full all its layers. Each row pools the test votes of the 20 random development/test splits of "
               "its regime.")
    if (work["variant"] == "Majority class (DEV)").any():
        caption += (" Majority class (DEV): the most frequent vote of each development split predicted for its "
                    "test votes; its pooled QWK can differ from 0 because the predicted class can change from "
                    "one split to another.")
    lines += ["\\bottomrule", "\\end{tabular}%", "}", f"\\caption{{{caption}}}\\label{{tab:phase3_adaptive}}",
              "\\end{table}"]
    return "\n".join(lines) + "\n"


def nn_analysis_table(df: pd.DataFrame) -> str:
    """The paper's NN table (``items.nn_case_rows``, E9b): target, n, primary_disagreement,
    primary_chance_disagreement, case_b_clusters, case_b_cluster_agreement, case_b_chance_cluster_agreement,
    case_c_pairs, case_c_agreement, case_c_chance_agreement."""
    work = df.copy()
    work["__t"] = work["target"].map({t: i for i, t in enumerate(TARGETS)})
    work = work.sort_values("__t")

    def pct(v):
        return "--" if pd.isna(v) else f"{100 * float(v):.1f}\\,\\%"

    def num(v):
        return f"{int(v):,}".replace(",", "\\,")
    lines = ["% Nearest-neighbour analysis as in the paper (E9b; the definitions of the original analysis",
             "% restored, data loaded with the category normalisation, 12 features (features_12), full cohort),",
             "% descriptive, each value beside its chance reference on the same votes. Generated by analysis/paper_figures.",
             "\\begin{table}[H]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\renewcommand{\\arraystretch}{0.95}", "\\begin{tabular}{lcccccccc}", "\\toprule",
             "& \\multicolumn{2}{c}{Nearest neighbour} & \\multicolumn{3}{c}{Case B: identical feature vectors} & "
             "\\multicolumn{3}{c}{Case C: pairs within tight margins} \\\\",
             "Target & Disagreement & Chance disagr. & Groups & Agreement & Chance agr. & Pairs & Agreement & "
             "Chance agr. \\\\",
             "\\midrule"]
    for _, r in work.iterrows():
        lines.append(f"{TARGET_LABEL[r['target']]} & {pct(r['primary_disagreement'])} & "
                     f"{pct(r['primary_chance_disagreement'])} & {num(r['case_b_clusters'])} & "
                     f"{pct(r['case_b_cluster_agreement'])} & {pct(r['case_b_chance_cluster_agreement'])} & "
                     f"{num(r['case_c_pairs'])} & {pct(r['case_c_agreement'])} & {pct(r['case_c_chance_agreement'])} "
                     "\\\\")
    n = int(work["n"].iloc[0])
    rows_col = work["case_b_rows"] if "case_b_rows" in work.columns else work["case_b_clusters"]
    groups = sorted({(int(g), int(v)) for g, v in zip(work["case_b_clusters"], rows_col)})
    groups_txt = "; ".join(f"{num(g)} groups, {num(v)} votes" for g, v in groups)
    caption = (f"Vote agreement between ASHRAE-2022 votes that are close or identical in the space of the 12 "
               f"variables (the {num(n)} cohort votes). Nearest neighbour: each vote is compared with the vote of "
               "its nearest other vote (Euclidean distance, categorical variables integer-coded, every variable "
               "standardised); disagreement = share of votes that differ from it; chance = $1-\\sum_c p_c^2$ "
               "($p_c$: class shares of the cohort votes). Case B: groups of votes whose feature vectors are "
               "identical (numerical variables rounded to 3 decimals); agreement = share of groups whose votes all "
               "agree; chance = mean over the groups of $\\sum_c q_c^{n_g}$ ($q_c$: class shares of the grouped "
               f"votes, $n_g$: group size; Case B rests on {groups_txt}). Case C: pairs of votes with the same "
               "categorical variables and age, and "
               "air temperature within 1\\,\\textdegree C, outdoor temperature within 1\\,\\textdegree C, "
               "relative humidity within 5 points, air speed within 0.3\\,m/s, clothing within 0.3\\,clo and "
               "metabolic rate within 0.2\\,met; agreement = share of these pairs with the same vote; chance = "
               "$\\sum_c p_c^2$ ($p_c$: class shares of the paired votes, each vote counted once per pair). "
               "Descriptive statistics.")
    lines += ["\\bottomrule", "\\end{tabular}", f"\\caption{{{caption}}}\\label{{tab:nn_disagreement}}",
              "\\end{table}"]
    return "\n".join(lines) + "\n"
